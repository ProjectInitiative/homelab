#!/usr/bin/env python3
"""
codex-sync-models.py — regenerate the ChatGPT/Codex model_list block for
ai-proxy-config from the live backend catalog.

The Codex backend (chatgpt.com/backend-api/codex) has no model-listing that
litellm's chatgpt/ provider consumes natively, and its lineup rotates (the
litellm docs' gpt-5.3-codex family is already rejected). This script queries
the authoritative catalog and emits the model_list entries (plain + -gated
twins) so the proxy's /v1/models — and pi's discovery extension — stay current.

Usage (single line, from a pod or any host with the token PVC + kubectl):
  python3 codex-sync-models.py            # prints the YAML block to stdout

In-cluster (token on the litellm-chatgpt-tokens PVC):
  kubectl run codex-sync --rm -i --restart=Never --image=ghcr.io/berriai/litellm@sha256:87f349... \
    --overrides='... mount PVC at /t and this script ...' < codex-sync-models.py

Catalog notes:
  - endpoint: GET https://chatgpt.com/backend-api/codex/models?client_version=1.0.0
    (version-gated: older client_version returns an empty list)
  - auth: Bearer access_token + ChatGPT-Account-Id from auth.json on the PVC
  - `codex` / `codex-gated` are stable aliases pinned to the newest *sol
    workhorse model; per-slug aliases are generated for everything else.
"""
import json
import sys
import urllib.request

TOKEN_PATHS = ["/t/auth.json", "/tokens/chatgpt/auth.json"]


def load_auth() -> dict:
    for p in TOKEN_PATHS:
        try:
            return json.load(open(p))
        except OSError:
            continue
    raise SystemExit("auth.json not found; mount the token PVC and retry")


def fetch_catalog() -> list[dict]:
    a = load_auth()
    req = urllib.request.Request(
        "https://chatgpt.com/backend-api/codex/models?client_version=1.0.0",
        headers={
            "Authorization": "Bearer " + a["access_token"],
            "ChatGPT-Account-Id": a.get("account_id", ""),
            "User-Agent": "codex_cli_rs",
            "originator": "codex_cli_rs",
        },
    )
    d = json.loads(urllib.request.urlopen(req, timeout=30).read().decode())
    return d.get("models", [])


def emit(models: list[dict]) -> None:
    # stable "latest" alias: newest sol workhorse per the catalog description
    sols = [m["slug"] for m in models if "sol" in m["slug"]]
    latest = max(sols, key=lambda s: tuple(int(x) for x in s.split("-")[1].split("."))) if sols else None
    seen = set()
    out = []
    for m in models:
        slug = m["slug"]
        if slug in seen:
            continue
        seen.add(slug)
        ctx = m.get("max_context_window") or m.get("context_window") or 272000
        for alias, gated in ((slug, False), (slug + "-gated", True)):
            comment = (
                "      # stable alias: latest sol workhorse\n"
                if alias == "codex"
                else ""
            )
            out.append(
                f"{comment}      - model_name: {alias}\n"
                f"        litellm_params:\n"
                f"          model: chatgpt/{latest if alias == 'codex' else slug}\n"
                f"        model_info:\n"
                f"          mode: responses\n"
                f"          max_input_tokens: {ctx}\n"
                f"          disable_background_health_check: true\n"
            )
    if latest:
        for alias in ("codex", "codex-gated"):
            out.append(
                f"      - model_name: {alias}\n"
                f"        litellm_params:\n"
                f"          model: chatgpt/{latest}\n"
                f"        model_info:\n"
                f"          mode: responses\n"
                f"          disable_background_health_check: true\n"
            )
    print("".join(out))


if __name__ == "__main__":
    models = fetch_catalog()
    if not models:
        raise SystemExit("catalog returned no models — check client_version/token")
    print(f"# generated by codex-sync-models.py from {len(models)} catalog models", file=sys.stderr)
    emit(models)
